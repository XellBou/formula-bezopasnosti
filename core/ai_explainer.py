def _get_api_key() -> str | None:
    key = os.environ.get("OPENAI_API_KEY", "").strip()
    return key or None


def is_demo_mode() -> bool:
    """True, если ключ OpenAI не задан и используются шаблонные ответы."""
    return _get_api_key() is None


def _demo_answer(prompt: str, fallback: str | None = None) -> str:
    if fallback:
        return fallback + DEMO_NOTE
    text = prompt.lower()
    for keywords, answer in DEMO_TEMPLATES:
        if any(word in text for word in keywords):
            return answer + DEMO_NOTE
    return GENERIC_DEMO + DEMO_NOTE


def explain(prompt: str, fallback: str | None = None) -> str:
    """Возвращает объяснение для курсанта.

    prompt   — вопрос/контекст для объяснения.
    fallback — необязательный готовый текст для демо-режима (например, локальный разбор задачи).
    Без OPENAI_API_KEY возвращается шаблонный ответ; ошибки API не приводят к падению приложения.
    """
    prompt = (prompt or "").strip()
    if not prompt:
        return "Не получен вопрос для объяснения. Введите исходные данные и попробуйте ещё раз."

    api_key = _get_api_key()
    if not api_key:
        return _demo_answer(prompt, fallback)

    try:
        from openai import OpenAI
    except ImportError:
        return (
            "⚠️ Библиотека openai не установлена (выполните `pip install -r requirements.txt`). "
            "Пока показываю шаблонное объяснение.\n\n" + _demo_answer(prompt, fallback)
        )

    try:
        client = OpenAI(api_key=api_key, timeout=30.0, max_retries=1)
        response = client.chat.completions.create(
            model=os.environ.get("OPENAI_MODEL", DEFAULT_MODEL),
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            temperature=0.4,
            max_tokens=500,
        )
        text = (response.choices[0].message.content or "").strip()
        if not text:
            return "⚠️ ИИ вернул пустой ответ. Попробуйте ещё раз.\n\n" + _demo_answer(prompt, fallback)
        return text
    except Exception as exc:  # сеть, неверный ключ, лимиты и т. п.
        details = str(exc).strip().replace("\n", " ")[:200]
        return (
            f"⚠️ Не удалось получить объяснение от ИИ ({type(exc).__name__}: {details}). "
            "Проверьте ключ OPENAI_API_KEY, подключение к интернету и лимиты. "
            "Пока показываю шаблонное объяснение.\n\n" + _demo_answer(prompt, fallback)
        )


def explain_block(
    prompt: str,
    key: str,
    fallback: str | None = None,
    label: str = "🎓 Объясни как курсанту",
) -> None:
    """Кнопка + вывод объяснения. Ответ хранится в session_state и сбрасывается при смене данных."""
    state_key = f"ai_answer_{key}"
    if st.button(label, key=f"ai_btn_{key}"):
        with st.spinner("Готовлю объяснение…"):
            st.session_state[state_key] = {"prompt": prompt, "answer": explain(prompt, fallback=fallback)}
    stored = st.session_state.get(state_key)
    if stored and stored.get("prompt") == prompt:
        st.info(stored["answer"])